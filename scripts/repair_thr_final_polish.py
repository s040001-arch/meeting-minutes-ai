def apply_fixes(text: str) -> tuple[str, int, list[str]]:
    applied = 0
    missing: list[str] = []
    for old, new in FIXES:
        c = text.count(old)
        if c == 0:
            missing.append(old)
            continue
        text = text.replace(old, new)
        applied += c
    return text, applied, missing


